"""Generate Web font faces from the shared catalog; no runtime build is required."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
resources = root / 'Packages/LittleDaysCore/Sources/LittleDaysCore/Resources'
catalog = json.loads((resources / 'library.json').read_text(encoding='utf-8'))
css = '/* Generated by tools/sync_library.py. Font sources and OFL notices: shared library.json. */\n'
for font in catalog['fonts']:
    for name in [font['file'], font['license']]:
        if not (resources / 'Fonts' / name).is_file():
            raise FileNotFoundError(name)
    weights = f"{font['weightMin']} {font['weightMax']}" if font['weightMin'] != font['weightMax'] else str(font['weightMin'])
    css += f'@font-face {{ font-family: "{font["family"]}"; src: url("library/fonts/{font["file"]}") format("truetype"); font-weight: {weights}; font-style: normal; font-display: swap; }}\n'
(root / 'Public/fonts.css').write_text(css, encoding='utf-8')
