"""Regenerate the Web colors from the shared Swift resource.

1. Public/tokens.css  – the named design colors (cream, ink, accent, …).
2. Public/styles.css  – every literal hex color becomes
   `var(--c-xxxxxx, #xxxxxx)`, so the default look is unchanged (the literal
   is the fallback) while a theme can recolor it. Re-running is idempotent and
   also converts colors added by hand later.
3. Public/themes.css  – one block per app theme from design-tokens.json
   "themes", computed from each color. Journal paper, covers, spines and the
   photo editor keep their real colors in every theme (they are "paper").
"""
import colorsys
import json
import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
tokens = json.loads((root / 'Packages/LittleDaysCore/Sources/LittleDaysCore/Resources/design-tokens.json').read_text(encoding='utf-8'))

css = '/* Generated by tools/sync_tokens.py. Do not edit directly. */\n:root {\n'
css += ''.join(f'  --{name}: {value};\n' for name, value in tokens['colors'].items())
css += '}\n'
(root / 'Public/tokens.css').write_text(css, encoding='utf-8')

# ---- 2. literal colors → variables with the literal as fallback ----
styles_path = root / 'Public/styles.css'
styles = styles_path.read_text(encoding='utf-8')
HEX = re.compile(r'(?<![\w-])#([0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{3})\b')
WRAPPED = re.compile(r'var\(--[ct]-[0-9a-f]+, #[0-9a-fA-F]+\)')
# Text colors get their own variables (--t-…): a dark theme turns every
# text light, while surfaces (--c-…) turn dark.
TEXT_DECL = re.compile(r'((?<![\w-])(?:color|fill|stroke|caret-color|-webkit-text-fill-color)\s*:)([^;{}]*)')


def norm(value):
    value = value.lower()
    return ''.join(c * 2 for c in value) if len(value) == 3 else value


def wrap(text):
    out, last = [], 0
    for m in WRAPPED.finditer(text):
        out.append(HEX.sub(lambda h: f'var(--c-{norm(h.group(1))}, #{h.group(1)})', text[last:m.start()]))
        out.append(m.group(0))
        last = m.end()
    out.append(HEX.sub(lambda h: f'var(--c-{norm(h.group(1))}, #{h.group(1)})', text[last:]))
    return ''.join(out)


# Leave @import lines and comments alone.
parts = re.split(r'(/\*.*?\*/)', styles, flags=re.S)
styles = ''.join(part if part.startswith('/*') else wrap(part) for part in parts)
styles = TEXT_DECL.sub(lambda m: m.group(1) + m.group(2).replace('var(--c-', 'var(--t-'), styles)
styles_path.write_text(styles, encoding='utf-8')
colors = sorted(set(re.findall(r'var\(--c-([0-9a-f]+),', styles)))
text_colors = sorted(set(re.findall(r'var\(--t-([0-9a-f]+),', styles)))

# ---- 3. themes ----


def rgba(hex_value):
    r, g, b = (int(hex_value[i:i + 2], 16) / 255 for i in (0, 2, 4))
    a = int(hex_value[6:8], 16) / 255 if len(hex_value) == 8 else None
    return r, g, b, a


def to_hex(r, g, b, a):
    out = '#' + ''.join(f'{round(max(0, min(1, v)) * 255):02x}' for v in (r, g, b))
    return out + (f'{round(a * 255):02x}' if a is not None else '')


def mix_hue(h, target, amount):
    delta = ((target - h + 0.5) % 1.0) - 0.5
    return (h + delta * amount) % 1.0


def transform(hex_value, theme):
    """Recolor one UI color for a theme. Near-neutral colors (creams, greys)
    take the theme's own light tint; colored ones move toward its hue."""
    r, g, b, a = rgba(hex_value)
    h, l, s = colorsys.rgb_to_hls(r, g, b)
    chroma = max(r, g, b) - min(r, g, b)
    hue = (theme.get('hue', 0) % 360) / 360
    sat = theme.get('saturation', 1.0)
    pull = theme.get('huePull', 0.7)
    tint = theme.get('tint', 0.03)
    dark = theme.get('mode') == 'dark'
    if dark:
        # Soft shadows stay shadows (dark), not glows.
        if a is not None and a < 0.5 and l < 0.5:
            return to_hex(0, 0, 0, min(1, a * 1.6))
        l = 0.1 + (1 - l) * 0.8
    accent = theme.get('colors', {}).get('accent')
    if chroma < 0.09:
        h, new_chroma = hue, tint
    elif accent and 0.16 < h < 0.42:
        # The default sage greens are the accent family: they take the
        # theme's accent hue and strength (navy, black, pink, teal…).
        ar, ag, ab, _ = rgba(accent.lstrip('#').lower())
        ah, al, as_ = colorsys.rgb_to_hls(ar, ag, ab)
        h, new_chroma = ah, min(0.6, chroma * (max(ar, ag, ab) - min(ar, ag, ab)) / 0.13)
        if dark:
            l = min(0.85, max(l, 0.55))
    else:
        h, new_chroma = mix_hue(h, hue, pull), min(0.6, chroma * sat)
    span = 1 - abs(2 * l - 1)
    s = min(1, new_chroma / span) if span > 0.001 else 0
    r, g, b = colorsys.hls_to_rgb(h, l, s)
    return to_hex(r, g, b, a)


def transform_text(hex_value, theme):
    """Text in a dark theme: always light (white stays white, dark ink and
    grey hints become light), keeping the hue of colored text."""
    if theme.get('mode') != 'dark':
        return transform(hex_value, theme)
    r, g, b, a = rgba(hex_value)
    h, l, s = colorsys.rgb_to_hls(r, g, b)
    if l > 0.85:
        return to_hex(r, g, b, a)
    shifted = rgba(transform(hex_value, theme).lstrip('#'))
    h2, _, s2 = colorsys.rgb_to_hls(*shifted[:3])
    l2 = 0.95 - l * 0.33
    r, g, b = colorsys.hls_to_rgb(h2, l2, min(s2, 0.55))
    return to_hex(r, g, b, a)


PAPER = '.journal-canvas, .book-cover, .spine, .shelf-plank, .toast, .layer-bar, .scene-dialog, .cal-wall, .work-cover, .photo-editor, .day-cover-photos, .journey-page, .cover-option, .hero-photo, .inspire-card img, .space-banner'
blocks = ['/* Generated by tools/sync_tokens.py from design-tokens.json "themes". Do not edit directly. */']
for theme in tokens.get('themes', []):
    if theme.get('id') == 'soft':
        continue
    sel = f':root[data-theme="{theme["id"]}"]'
    lines = [f'  --c-{c}: {transform(c, theme)};' for c in colors]
    lines += [f'  --t-{c}: {transform_text(c, theme)};' for c in text_colors]
    for name, value in tokens['colors'].items():
        lines.append(f'  --{name}: {theme.get("colors", {}).get(name) or transform(value.lstrip("#").lower(), theme)};')
    lines.append(f'  color-scheme: {"dark" if theme.get("mode") == "dark" else "light"};')
    blocks.append(f'{sel} {{\n' + '\n'.join(lines) + '\n}')
# Paper keeps its real colors in every theme.
paper = [f'  --c-{c}: #{c};' for c in colors] + [f'  --t-{c}: #{c};' for c in text_colors] + [f'  --{n}: {v};' for n, v in tokens['colors'].items()]
blocks.append(f':root[data-theme] :is({PAPER}) {{\n' + '\n'.join(paper) + '\n  color-scheme: light;\n}')
(root / 'Public/themes.css').write_text('\n'.join(blocks) + '\n', encoding='utf-8')
print(f'tokens: {len(tokens["colors"])} · colors in styles.css: {len(colors)} · themes: {len(tokens.get("themes", []))}')
